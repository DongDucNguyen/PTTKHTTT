--   #1 tblReview không còn verified_purchase / origin
--   #4 tblOrder có cột chụp địa chỉ giao hàng (ship_recipient, ship_phone, ship_address)
--   #5 tblPayment."paymentMethodId" cho phép NULL (COD / chuyển khoản)
-- Bổ sung: tblReturnItem."replacementVariantId" (biến thể thay thế khi đổi hàng).
-- Chạy trên một CSDL rỗng (setup_db.py lo việc này). CSDL cũ đã có dữ liệu: dùng migrate_v2.sql.

-- ---------------------------------------------------------------- user
CREATE TABLE "tblUser" (
    "id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "email"         varchar(255) NOT NULL UNIQUE,
    "password"      varchar(255) NOT NULL,
    "status"        varchar(50)  NOT NULL DEFAULT 'active' CHECK ("status" IN ('active','suspended')),
    "created_at"    timestamp    NOT NULL DEFAULT now(),
    "last_login_at" timestamp
);
CREATE UNIQUE INDEX "ux_tblUser_email_lower" ON "tblUser" (lower("email"));

CREATE TABLE "tblCustomer" (
    "id"                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "full_name"         varchar(255) NOT NULL,
    "phone"             varchar(20),
    "marketing_consent" boolean NOT NULL DEFAULT false,
    "preferred_colours" varchar(255),
    "userId"            integer NOT NULL UNIQUE REFERENCES "tblUser"("id") ON DELETE CASCADE
);

CREATE TABLE "tblStaffMember" (
    "id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "code"      varchar(20)  NOT NULL UNIQUE,
    "full_name" varchar(255) NOT NULL,
    "role"      varchar(50)  NOT NULL CHECK ("role" IN ('administrator','manager','merchandiser','marketing',
                                                       'customer_service','warehouse','sales')),
    "userId"    integer NOT NULL UNIQUE REFERENCES "tblUser"("id") ON DELETE CASCADE
);

CREATE TABLE "tblSupplier" (
    "id"     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"   varchar(255) NOT NULL,
    "email"  varchar(255),
    "phone"  varchar(20),
    "userId" integer UNIQUE REFERENCES "tblUser"("id") ON DELETE SET NULL
);

-- ---------------------------------------------------------------- catalogue
CREATE TABLE "tblCategory" (
    "id"       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"     varchar(100) NOT NULL,
    "parentId" integer REFERENCES "tblCategory"("id") ON DELETE RESTRICT,
    CHECK ("parentId" IS NULL OR "parentId" <> "id")
);

CREATE TABLE "tblCollection" (
    "id"     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"   varchar(100) NOT NULL,
    "season" varchar(50)  NOT NULL CHECK ("season" IN ('spring_summer','autumn_winter','all_season')),
    "year"   integer NOT NULL CHECK ("year" BETWEEN 2000 AND 2100)
);

CREATE TABLE "tblStyle" (
    "id"                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "code"              varchar(30)  NOT NULL UNIQUE,
    "name"              varchar(255) NOT NULL,
    "description"       varchar(2000),
    "brand"             varchar(100),
    "fit_type"          varchar(50) CHECK ("fit_type" IN ('slim','regular','relaxed','oversized')),
    "care_instructions" varchar(1000),
    "features"          varchar(1000),
    "model_info"        varchar(500),
    "status"            varchar(50) NOT NULL DEFAULT 'draft' CHECK ("status" IN ('draft','active','inactive')),
    "categoryId"        integer NOT NULL REFERENCES "tblCategory"("id") ON DELETE RESTRICT,
    "supplierId"        integer NOT NULL REFERENCES "tblSupplier"("id") ON DELETE RESTRICT,
    "collectionId"      integer REFERENCES "tblCollection"("id") ON DELETE SET NULL
);

CREATE TABLE "tblProductVariant" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "sku"        varchar(50) NOT NULL UNIQUE,
    "size_label" varchar(20) NOT NULL,
    "colour"     varchar(50) NOT NULL,
    "price"      integer NOT NULL CHECK ("price" > 0),
    "status"     varchar(50) NOT NULL DEFAULT 'active' CHECK ("status" IN ('active','discontinued')),
    "styleId"    integer NOT NULL REFERENCES "tblStyle"("id") ON DELETE RESTRICT,
    UNIQUE ("styleId", "size_label", "colour")
);

CREATE TABLE "tblProductMedia" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "url"        varchar(500) NOT NULL,
    "media_type" varchar(50) NOT NULL CHECK ("media_type" IN ('image','video')),
    "colour"     varchar(50),
    "sort_order" integer NOT NULL DEFAULT 1 CHECK ("sort_order" >= 0),
    "styleId"    integer NOT NULL REFERENCES "tblStyle"("id") ON DELETE CASCADE
);

CREATE TABLE "tblMaterialComponent" (
    "id"       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "material" varchar(100) NOT NULL,
    "percent"  integer NOT NULL CHECK ("percent" BETWEEN 1 AND 100),
    "styleId"  integer NOT NULL REFERENCES "tblStyle"("id") ON DELETE CASCADE
);

CREATE TABLE "tblSizeChartEntry" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "size_label" varchar(20) NOT NULL,
    "measure"    varchar(50) NOT NULL CHECK ("measure" IN ('chest','waist','hip','length','sleeve','inseam','foot_length')),
    "value_cm"   real NOT NULL CHECK ("value_cm" > 0),
    "styleId"    integer NOT NULL REFERENCES "tblStyle"("id") ON DELETE CASCADE,
    UNIQUE ("styleId", "size_label", "measure")
);

-- ---------------------------------------------------------------- customer data
CREATE TABLE "tblAddress" (
    "id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "recipient_name" varchar(255) NOT NULL,
    "phone"          varchar(20)  NOT NULL,
    "street"         varchar(255) NOT NULL,
    "ward"           varchar(100) NOT NULL,
    "district"       varchar(100) NOT NULL,
    "city"           varchar(100) NOT NULL,
    "is_default"     boolean NOT NULL DEFAULT false,
    "customerId"     integer NOT NULL REFERENCES "tblCustomer"("id") ON DELETE CASCADE
);

CREATE TABLE "tblNotification" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "channel"    varchar(50) NOT NULL CHECK ("channel" IN ('email','sms','app')),
    "event_type" varchar(50) NOT NULL CHECK ("event_type" IN ('order_confirmed','order_shipped','order_delivered',
                         'order_cancelled','return_authorised','return_rejected','refund_completed','exchange_shipped')),
    "message"    varchar(1000) NOT NULL,
    "status"     varchar(50) NOT NULL DEFAULT 'queued' CHECK ("status" IN ('queued','sent','failed')),
    "sent_at"    timestamp,
    "customerId" integer NOT NULL REFERENCES "tblCustomer"("id") ON DELETE CASCADE
);

CREATE TABLE "tblPaymentMethod" (
    "id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "provider"      varchar(100) NOT NULL,
    "method_type"   varchar(50)  NOT NULL CHECK ("method_type" IN ('card','e_wallet','bank_account')),
    "masked_number" varchar(30)  NOT NULL CHECK ("masked_number" LIKE '%*%'),
    "is_default"    boolean NOT NULL DEFAULT false,
    "customerId"    integer NOT NULL REFERENCES "tblCustomer"("id") ON DELETE CASCADE
);

CREATE TABLE "tblSavedSize" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "size_label" varchar(20) NOT NULL,
    "customerId" integer NOT NULL REFERENCES "tblCustomer"("id") ON DELETE CASCADE,
    "categoryId" integer NOT NULL REFERENCES "tblCategory"("id") ON DELETE CASCADE,
    UNIQUE ("customerId", "categoryId")
);

-- ---------------------------------------------------------------- audit
CREATE TABLE "tblAuditLogEntry" (
    "id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "entity"        varchar(100) NOT NULL,
    "action"        varchar(50)  NOT NULL CHECK ("action" IN ('create','update','deactivate','adjust_stock',
                                                            'suspend_account','reset_password')),
    "changes"       varchar(4000),
    "created_at"    timestamp NOT NULL DEFAULT now(),
    "staffMemberId" integer NOT NULL REFERENCES "tblStaffMember"("id") ON DELETE RESTRICT
);

-- ---------------------------------------------------------------- inventory
CREATE TABLE "tblStockLocation" (
    "id"      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"    varchar(100) NOT NULL UNIQUE,
    "address" varchar(255)
);

CREATE TABLE "tblStockLevel" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "on_hand"          integer NOT NULL DEFAULT 0 CHECK ("on_hand" >= 0),
    "reserved"         integer NOT NULL DEFAULT 0,
    "reorder_point"    integer NOT NULL DEFAULT 0 CHECK ("reorder_point" >= 0),
    "available"        integer NOT NULL DEFAULT 0,
    "productVariantId" integer NOT NULL UNIQUE REFERENCES "tblProductVariant"("id") ON DELETE CASCADE,
    "stockLocationId"  integer NOT NULL REFERENCES "tblStockLocation"("id") ON DELETE RESTRICT,
    CHECK ("reserved" >= 0 AND "reserved" <= "on_hand"),
    CHECK ("available" = "on_hand" - "reserved")
);

CREATE TABLE "tblStockMovement" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "quantity_change"  integer NOT NULL CHECK ("quantity_change" <> 0),
    "reason"           varchar(50) NOT NULL CHECK ("reason" IN ('sale','return','restock','adjustment')),
    "reference"        varchar(100),
    "note"             varchar(500),
    "created_at"       timestamp NOT NULL DEFAULT now(),
    "productVariantId" integer NOT NULL REFERENCES "tblProductVariant"("id") ON DELETE RESTRICT,
    "stockLocationId"  integer NOT NULL REFERENCES "tblStockLocation"("id") ON DELETE RESTRICT,
    "staffMemberId"    integer REFERENCES "tblStaffMember"("id") ON DELETE SET NULL
);

CREATE TABLE "tblRestockRequest" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "request_no"      varchar(30) NOT NULL UNIQUE,
    "status"          varchar(50) NOT NULL DEFAULT 'draft' CHECK ("status" IN ('draft','sent','confirmed','received','cancelled')),
    "created_at"      timestamp NOT NULL DEFAULT now(),
    "expected_date"   date,
    "supplier_note"   varchar(1000),
    "confirm_at"      date,
    "supplierId"      integer NOT NULL REFERENCES "tblSupplier"("id") ON DELETE RESTRICT,
    "stockLocationId" integer NOT NULL REFERENCES "tblStockLocation"("id") ON DELETE RESTRICT,
    "staffMemberId"   integer REFERENCES "tblStaffMember"("id") ON DELETE SET NULL
);

CREATE TABLE "tblRestockItem" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "quantity"         integer NOT NULL CHECK ("quantity" > 0),
    "restockRequestId" integer NOT NULL REFERENCES "tblRestockRequest"("id") ON DELETE CASCADE,
    "productVariantId" integer NOT NULL REFERENCES "tblProductVariant"("id") ON DELETE RESTRICT,
    UNIQUE ("restockRequestId", "productVariantId")
);

-- ---------------------------------------------------------------- sales
CREATE TABLE "tblCart" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "updated_at" timestamp NOT NULL DEFAULT now(),
    "subtotal"   integer NOT NULL DEFAULT 0 CHECK ("subtotal" >= 0),
    "customerId" integer NOT NULL UNIQUE REFERENCES "tblCustomer"("id") ON DELETE CASCADE
);

CREATE TABLE "tblCartItem" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "quantity"         integer NOT NULL CHECK ("quantity" > 0),
    "added_at"         timestamp NOT NULL DEFAULT now(),
    "cartId"           integer NOT NULL REFERENCES "tblCart"("id") ON DELETE CASCADE,
    "productVariantId" integer NOT NULL REFERENCES "tblProductVariant"("id") ON DELETE CASCADE,
    UNIQUE ("cartId", "productVariantId")
);

CREATE TABLE "tblPromotion" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"            varchar(255) NOT NULL,
    "promo_type"      varchar(50) NOT NULL CHECK ("promo_type" IN ('seasonal','flash_sale','clearance','loyalty')),
    "discount_type"   varchar(50) NOT NULL CHECK ("discount_type" IN ('percent','fixed_amount')),
    "discount_value"  integer NOT NULL CHECK ("discount_value" > 0),
    "min_order_value" integer NOT NULL DEFAULT 0 CHECK ("min_order_value" >= 0),
    "starts_at"       timestamp NOT NULL,
    "ends_at"         timestamp NOT NULL,
    "status"          varchar(50) NOT NULL DEFAULT 'draft' CHECK ("status" IN ('draft','active','ended')),
    CHECK ("ends_at" > "starts_at"),
    CHECK ("discount_type" <> 'percent' OR "discount_value" BETWEEN 1 AND 100)
);

CREATE TABLE "tblPromotionStyle" (
    "id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "promotionId" integer NOT NULL REFERENCES "tblPromotion"("id") ON DELETE CASCADE,
    "styleId"     integer NOT NULL REFERENCES "tblStyle"("id") ON DELETE CASCADE,
    UNIQUE ("promotionId", "styleId")
);

CREATE TABLE "tblVoucher" (
    "id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "code"        varchar(30) NOT NULL UNIQUE,
    "usage_limit" integer NOT NULL CHECK ("usage_limit" > 0),
    "used_count"  integer NOT NULL DEFAULT 0,
    "promotionId" integer NOT NULL REFERENCES "tblPromotion"("id") ON DELETE CASCADE,
    CHECK ("used_count" >= 0 AND "used_count" <= "usage_limit")
);
CREATE UNIQUE INDEX "ux_tblVoucher_code_upper" ON "tblVoucher" (upper("code"));

CREATE TABLE "tblOrder" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_no"         varchar(30) NOT NULL UNIQUE,
    "status"           varchar(50) NOT NULL DEFAULT 'pending_payment' CHECK ("status" IN ('pending_payment','confirmed',
                           'processing','partially_shipped','shipped','delivered','completed','cancelled')),
    "placed_at"        timestamp NOT NULL DEFAULT now(),
    "subtotal"         integer NOT NULL CHECK ("subtotal" >= 0),
    "discount"         integer NOT NULL DEFAULT 0 CHECK ("discount" >= 0),
    "shipping_fee"     integer NOT NULL DEFAULT 0 CHECK ("shipping_fee" >= 0),
    "grand_total"      integer NOT NULL CHECK ("grand_total" >= 0),
    "delivery_service" varchar(50) NOT NULL DEFAULT 'standard' CHECK ("delivery_service" IN ('standard','express')),
    "note"             varchar(1000),
    "cancel_reason"    varchar(1000),
    "ship_recipient"   varchar(255),
    "ship_phone"       varchar(20),
    "ship_address"     varchar(500),
    "customerId"       integer NOT NULL REFERENCES "tblCustomer"("id") ON DELETE RESTRICT,
    CHECK ("grand_total" = "subtotal" - "discount" + "shipping_fee")
);

CREATE TABLE "tblOrderItem" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "quantity"         integer NOT NULL CHECK ("quantity" > 0),
    "unit_price"       integer NOT NULL CHECK ("unit_price" >= 0),
    "discount"         integer NOT NULL DEFAULT 0 CHECK ("discount" >= 0),
    "line_total"       integer NOT NULL CHECK ("line_total" >= 0),
    "orderId"          integer NOT NULL REFERENCES "tblOrder"("id") ON DELETE CASCADE,
    "productVariantId" integer NOT NULL REFERENCES "tblProductVariant"("id") ON DELETE RESTRICT,
    UNIQUE ("orderId", "productVariantId"),
    CHECK ("line_total" = "quantity" * "unit_price" - "discount")
);

CREATE TABLE "tblOrderVoucher" (
    "id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "orderId"   integer NOT NULL REFERENCES "tblOrder"("id") ON DELETE CASCADE,
    "voucherId" integer NOT NULL REFERENCES "tblVoucher"("id") ON DELETE RESTRICT,
    UNIQUE ("orderId", "voucherId")
);

CREATE TABLE "tblPayment" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "kind"            varchar(50) NOT NULL CHECK ("kind" IN ('charge','refund')),
    "method"          varchar(50) NOT NULL CHECK ("method" IN ('cod','card','e_wallet','bank_transfer')),
    "amount"          integer NOT NULL CHECK ("amount" > 0),
    "status"          varchar(50) NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending','succeeded','failed')),
    "transaction_ref" varchar(100),
    "created_at"      timestamp NOT NULL DEFAULT now(),
    "orderId"         integer NOT NULL REFERENCES "tblOrder"("id") ON DELETE RESTRICT,
    "paymentMethodId" integer REFERENCES "tblPaymentMethod"("id") ON DELETE RESTRICT
);

-- ---------------------------------------------------------------- returns
CREATE TABLE "tblReturnRequest" (
    "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "return_no"          varchar(30) NOT NULL UNIQUE,
    "return_type"        varchar(50) NOT NULL CHECK ("return_type" IN ('return','exchange')),
    "reason_code"        varchar(50) NOT NULL CHECK ("reason_code" IN ('too_small','too_large','defect','wrong_item',
                                                                     'not_as_described','changed_mind')),
    "reason_detail"      varchar(1000),
    "desired_resolution" varchar(50) NOT NULL CHECK ("desired_resolution" IN ('refund','exchange')),
    "status"             varchar(50) NOT NULL DEFAULT 'requested' CHECK ("status" IN ('requested','authorised','rejected',
                             'in_transit','inspected','refunded','exchanged','closed')),
    "requested_at"       timestamp NOT NULL DEFAULT now(),
    "decided_at"         timestamp,
    "decision_note"      varchar(1000),
    "orderId"            integer NOT NULL UNIQUE REFERENCES "tblOrder"("id") ON DELETE RESTRICT,
    "staffMemberId"      integer REFERENCES "tblStaffMember"("id") ON DELETE SET NULL
);

CREATE TABLE "tblReturnItem" (
    "id"                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "quantity"             integer NOT NULL CHECK ("quantity" > 0),
    "inspection_result"    varchar(50) NOT NULL DEFAULT 'pending' CHECK ("inspection_result" IN ('pending','passed','failed')),
    "inspection_note"      varchar(1000),
    "returnRequestId"      integer NOT NULL REFERENCES "tblReturnRequest"("id") ON DELETE CASCADE,
    "orderItemId"          integer NOT NULL REFERENCES "tblOrderItem"("id") ON DELETE RESTRICT,
    "replacementVariantId" integer REFERENCES "tblProductVariant"("id") ON DELETE RESTRICT,
    UNIQUE ("returnRequestId", "orderItemId")
);

CREATE TABLE "tblReturnEvidence" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "url"             varchar(500) NOT NULL,
    "media_type"      varchar(50) NOT NULL CHECK ("media_type" IN ('image','video')),
    "returnRequestId" integer NOT NULL REFERENCES "tblReturnRequest"("id") ON DELETE CASCADE
);

-- ---------------------------------------------------------------- fulfilment
CREATE TABLE "tblShipment" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "direction"       varchar(50) NOT NULL CHECK ("direction" IN ('outbound','return')),
    "carrier"         varchar(100),
    "service_level"   varchar(50) NOT NULL DEFAULT 'standard' CHECK ("service_level" IN ('standard','express')),
    "tracking_no"     varchar(100),
    "fee"             integer NOT NULL DEFAULT 0 CHECK ("fee" >= 0),
    "status"          varchar(50) NOT NULL DEFAULT 'requested' CHECK ("status" IN ('requested','picked_up','in_transit',
                                                                                'delivered','failed')),
    "delivered_at"    timestamp,
    "orderId"         integer NOT NULL REFERENCES "tblOrder"("id") ON DELETE CASCADE,
    "stockLocationId" integer NOT NULL REFERENCES "tblStockLocation"("id") ON DELETE RESTRICT,
    "returnRequestId" integer REFERENCES "tblReturnRequest"("id") ON DELETE SET NULL,
    CHECK ("direction" = 'outbound' OR "returnRequestId" IS NOT NULL)
);

CREATE TABLE "tblShipmentEvent" (
    "id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "status"      varchar(50) NOT NULL CHECK ("status" IN ('requested','picked_up','in_transit','delivered','failed')),
    "occurred_at" timestamp NOT NULL DEFAULT now(),
    "note"        varchar(500),
    "shipmentId"  integer NOT NULL REFERENCES "tblShipment"("id") ON DELETE CASCADE,
    UNIQUE ("shipmentId", "status", "occurred_at")
);

CREATE TABLE "tblShipmentRecord" (
    "id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "quantity"    integer NOT NULL CHECK ("quantity" > 0),
    "shipmentId"  integer NOT NULL REFERENCES "tblShipment"("id") ON DELETE CASCADE,
    "orderItemId" integer NOT NULL REFERENCES "tblOrderItem"("id") ON DELETE CASCADE
);

-- ---------------------------------------------------------------- review
CREATE TABLE "tblReview" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "rating"          integer NOT NULL CHECK ("rating" BETWEEN 1 AND 5),
    "body"            varchar(4000) NOT NULL,
    "size_purchased"  varchar(20),
    "fit_vote"        varchar(50) CHECK ("fit_vote" IN ('runs_small','true_to_size','runs_large')),
    "status"          varchar(50) NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending','approved','rejected')),
    "moderation_note" varchar(1000),
    "created_at"      timestamp NOT NULL DEFAULT now(),
    "orderItemId"     integer NOT NULL UNIQUE REFERENCES "tblOrderItem"("id") ON DELETE CASCADE,
    "staffMemberId"   integer REFERENCES "tblStaffMember"("id") ON DELETE SET NULL
);

-- ---------------------------------------------------------------- assistant
CREATE TABLE "tblAssistantTurn" (
    "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "question"   varchar(2000) NOT NULL,
    "answer"     varchar(4000) NOT NULL,
    "mode"       varchar(50) NOT NULL CHECK ("mode" IN ('model','basic')),
    "model_name" varchar(100),
    "latency_ms" integer CHECK ("latency_ms" >= 0),
    "created_at" timestamp NOT NULL DEFAULT now(),
    "customerId" integer REFERENCES "tblCustomer"("id") ON DELETE SET NULL,
    "styleId"    integer REFERENCES "tblStyle"("id") ON DELETE SET NULL
);

CREATE TABLE "tblGroundingEvent" (
    "id"              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "check_name"      varchar(50) NOT NULL CHECK ("check_name" IN ('price','stock','fit','fabric','popularity','policy','health')),
    "removed_text"    varchar(2000) NOT NULL,
    "assistantTurnId" integer NOT NULL REFERENCES "tblAssistantTurn"("id") ON DELETE CASCADE
);

